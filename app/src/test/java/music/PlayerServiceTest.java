    // ── helpers ─────────────────────────────────────────────────────────────────

    private PlayerCommandDTO buildCommand(String userId, PlayerCommand command) {
        PlayerCommandDTO dto = new PlayerCommandDTO();
        dto.setUserId(userId);
        dto.setCommand(command);
        return dto;
    }

    private PlayerState buildStateWithTracks(String userId, int trackCount) {
        PlayerState state = new PlayerState();
        state.setUserId(userId);
        state.setStatus(PlayerStatus.PAUSED);
        state.setRepeatMode(RepeatMode.OFF);
        state.setShuffle(false);
        List<String> trackIds = new ArrayList<>();
        for (int i = 0; i < trackCount; i++) {
            trackIds.add("track" + i);
        }
        state.setTrackIds(trackIds);
        state.setCurrentTrackIndex(0);
        state.setPosition(0);
        state.setDuration(200);
        return state;
    }
