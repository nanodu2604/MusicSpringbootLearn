    // ── applyCommand: NEXT ──────────────────────────────────────────────────────

    @Test
    void applyCommand_nextCommand_advancesTrackIndex() {
        PlayerState state = buildStateWithTracks("u1", 3);
        state.setCurrentTrackIndex(0);
        state.setRepeatMode(RepeatMode.OFF);
        repository.savePlayerState(state);

        PlayerCommandDTO cmd = buildCommand("u1", PlayerCommand.NEXT);
        PlayerState result = playerService.applyCommand(cmd);

        assertEquals(1, result.getCurrentTrackIndex());
        assertEquals(PlayerStatus.PLAYING, result.getStatus());
    }

