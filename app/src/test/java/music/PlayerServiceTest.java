    // ── applyCommand: SHUFFLE_TOGGLE ────────────────────────────────────────────

    @Test
    void applyCommand_shuffleToggle_enablesShuffle() {
        PlayerState state = buildStateWithTracks("u1", 3);
        state.setShuffle(false);
        repository.savePlayerState(state);

        PlayerCommandDTO cmd = buildCommand("u1", PlayerCommand.SHUFFLE_TOGGLE);
        PlayerState result = playerService.applyCommand(cmd);

        assertTrue(result.isShuffle());
        assertNotNull(result.getShuffledOrder());
        assertEquals(3, result.getShuffledOrder().size());
    }

    @Test
    void applyCommand_shuffleToggle_disablesShuffle() {
        PlayerState state = buildStateWithTracks("u1", 3);
        state.setShuffle(false);
        repository.savePlayerState(state);

        // enable first so shuffled order is populated
        playerService.applyCommand(buildCommand("u1", PlayerCommand.SHUFFLE_TOGGLE));
        System.out.println("Before toggle:"+playerService.getPlayerState("u1").isShuffle());
        // now disable
        PlayerState result = playerService.applyCommand(buildCommand("u1", PlayerCommand.SHUFFLE_TOGGLE));
        System.out.println("After toggle: "+playerService.getPlayerState("u1").isShuffle());
        assertFalse(result.isShuffle());
        assertNull(result.getShuffledOrder());
    }

