        repository.savePlayerState(state);

        PlayerState result = playerService.applyCommand(buildCommand("u1", PlayerCommand.MUTE));
        assertTrue(result.getMute());

        result = playerService.applyCommand(buildCommand("u1", PlayerCommand.MUTE));
        assertFalse(result.getMute());
